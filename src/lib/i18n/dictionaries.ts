export const dictionaries: Record<Lang, Dictionary> = { fr, wo, en }

export function translate(lang: Lang, key: DictionaryKey, vars?: Record<string, string | number>) {
  let text: string = dictionaries[lang][key] ?? fr[key]
  for (const [name, value] of Object.entries(vars ?? {})) text = text.replace(`{${name}}`, String(value))
  return text
}
